def test_overwrite_requires_authorization(ws):
    ws.write_text("src/core.py", "existing\n")
    spec, design, plan = _ready()
    changes = propose_changes(spec, design, plan)
    prepared = prepare_generation(spec, design, plan, ws, changes)
    assert any(
        f.path == "src/core.py" and f.status == "rejected" for f in prepared.files
    )
    assert ws.read_text("src/core.py") == "existing\n"


def test_authorized_overwrite(ws):
    ws.write_text("README.md", "old\n")
    spec, design, plan = _ready()
    changes = propose_changes(spec, design, plan)
    for c in changes:
        if c.path == "README.md":
            c.overwrite = True
    prepared = prepare_generation(spec, design, plan, ws, changes)
    # core and tests may prepare; README should prepare as modify
    assert any(f.path == "README.md" and f.status == "prepared" for f in prepared.files)
    result = apply_generation(ws, changes, prepared)
    assert "Project" in ws.read_text("README.md") or "Generated" in ws.read_text("README.md")


def test_unprepared_not_applied(ws):
    spec, design, plan = _ready()
    changes = [FileChange(path="../x.py", content="x=1\n")]
    prepared = prepare_generation(spec, design, plan, ws, changes)
    result = apply_generation(ws, changes, prepared)
    assert result.success is False
    assert not ws.exists("../x.py")


def test_outside_unchanged(ws, tmp_path: Path):
    outside = tmp_path / "outside.txt"
    outside.write_text("keep")
    spec, design, plan = _ready()
    changes = [FileChange(path="../outside.txt", content="changed\n")]
    prepared = prepare_generation(spec, design, plan, ws, changes)
    apply_generation(ws, changes, prepared)
    assert outside.read_text() == "keep"


