"""Phase 6D: multi-file generation tests. Does not execute generated code."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from jarvis.dev.codegen import (
    FileChange,
    apply_generation,
    prepare_generation,
    propose_changes,
    BACKEND_DETERMINISTIC,
    GenerationError,
)
from jarvis.dev.models import SPEC_READY
from jarvis.dev.stages import analyze_requirements, design_architecture, build_plan
from jarvis.dev.workspace import WorkspaceManager, WorkspaceError


def _ready(request: str = "Language is Python. Build a hello function with unit tests."):
    r = analyze_requirements(request)
    assert r.spec is not None
    r.spec.status = SPEC_READY
    r.spec.clarifying_questions = []
    a = design_architecture(r.spec)
    p = build_plan(r.spec, a.design)
    assert a.success and p.success
    return r.spec, a.design, p.plan


@pytest.fixture
def ws(tmp_path: Path):
    return WorkspaceManager(tmp_path / "ws").create_project("demo")


def test_prepare_multiple_files(ws):
    spec, design, plan = _ready()
    prepared = prepare_generation(spec, design, plan, ws)
    assert prepared.prepared
    assert prepared.backend == BACKEND_DETERMINISTIC
    paths = [f.path for f in prepared.files if f.status == "prepared"]
    assert "src/core.py" in paths
    assert "tests/test_core.py" in paths
    assert "README.md" in paths
    assert not ws.exists("src/core.py")


def test_apply_creates_files(ws):
    spec, design, plan = _ready()
    changes = propose_changes(spec, design, plan)
    prepared = prepare_generation(spec, design, plan, ws, changes)
    result = apply_generation(ws, changes, prepared)
    assert result.success
    assert ws.read_text("src/core.py").startswith('"""Generated by Jarvis')
    assert "PLACEHOLDER" in ws.read_text("README.md") or "Template:" in ws.read_text("README.md")
    assert result.manifest_path
    manifest = json.loads(ws.read_text(result.manifest_path))
    assert manifest["backend"] == BACKEND_DETERMINISTIC
    assert any(f["status"] == "applied" for f in manifest["files"])


def test_traceability(ws):
    spec, design, plan = _ready()
    changes = propose_changes(spec, design, plan)
    assert changes[0].criterion_ids
    assert changes[0].plan_task_ids


def test_invalid_plan_rejected(ws):
    spec, design, plan = _ready()
    plan.status = "PENDING"
    result = prepare_generation(spec, design, plan, ws)
    assert result.success is False
    assert "not ready" in (result.error or "").lower()


def test_duplicate_paths_rejected(ws):
    spec, design, plan = _ready()
    changes = [
        FileChange(path="src/a.py", content="x=1\n", plan_task_ids=["implement_core"]),
        FileChange(path="src/a.py", content="x=2\n", plan_task_ids=["implement_core"]),
    ]
    result = prepare_generation(spec, design, plan, ws, changes)
    assert any(f.status == "rejected" and "duplicate" in (f.error or "") for f in result.files)


