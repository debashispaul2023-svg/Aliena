"""Controlled multi-file code generation (Phase 6D).

Prepares and applies file changes inside a DevWorkspace.
Does not execute generated code, run subprocesses, or install packages.

Backend: deterministic template only. Not a live AI coder.
"""

from __future__ import annotations

import hashlib
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional

from jarvis.dev.models import DesignDoc, RequirementSpec, SPEC_READY
from jarvis.dev.stages.planning import ImplementationPlan, PLAN_READY
from jarvis.dev.intelligence import detect_project_type
from jarvis.dev.templates import get_template, is_supported
from jarvis.dev.workspace import DevWorkspace, WorkspaceError

SCHEMA_VERSION = "1.0"
BACKEND_DETERMINISTIC = "deterministic_template"


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat()


def _new_id(prefix: str) -> str:
    return f"{prefix}{uuid.uuid4().hex[:12]}"


@dataclass
class FileChange:
    path: str
    content: str
    operation: str = "create"  # create | modify
    plan_task_ids: list[str] = field(default_factory=list)
    criterion_ids: list[str] = field(default_factory=list)
    overwrite: bool = False

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class FileResult:
    path: str
    status: str  # prepared | applied | rejected | failed
    operation: str = "create"
    sha256: Optional[str] = None
    error: Optional[str] = None
    plan_task_ids: list[str] = field(default_factory=list)
    criterion_ids: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class GenerationResult:
    operation_id: str
    project_id: str
    success: bool
    prepared: bool = False
    applied: bool = False
    backend: str = BACKEND_DETERMINISTIC
    files: list[FileResult] = field(default_factory=list)
    manifest_path: Optional[str] = None
    error: Optional[str] = None
    incomplete_tasks: list[str] = field(default_factory=list)
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": SCHEMA_VERSION,
            "operation_id": self.operation_id,
            "project_id": self.project_id,
            "success": self.success,
            "prepared": self.prepared,
            "applied": self.applied,
            "backend": self.backend,
            "files": [f.to_dict() for f in self.files],
            "manifest_path": self.manifest_path,
            "error": self.error,
            "incomplete_tasks": list(self.incomplete_tasks),
            "notes": self.notes,
        }


class GenerationError(ValueError):
    """Invalid generation request."""


def _hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def deterministic_content(
    *,
    path: str,
    plan_task_id: str,
    criterion_ids: list[str],
    overview: str,
) -> str:
    """Deterministic fixture content. Not AI-generated."""
    return (
        f'"""Generated by Jarvis Phase 6D deterministic template.\n'
        f"path: {path}\n"
        f"plan: {plan_task_id}\n"
        f"criteria: {','.join(criterion_ids)}\n"
        f'"""\n\n'
        f"PROJECT_TYPE = {detect_project_type(overview)!r}\nTEMPLATE = {get_template(detect_project_type(overview)).get('id')!r}\nOVERVIEW = {overview!r}\n"
    )


def _header(path: str, plan_task_id: str, criterion_ids: list[str], overview: str) -> str:
    ptype = detect_project_type(overview)
    return (
        f'"""Generated by Jarvis deterministic template.\n'
        f"path: {path}\n"
        f"plan: {plan_task_id}\n"
        f"criteria: {','.join(criterion_ids)}\n"
        f'"""\n'
        f"PROJECT_TYPE = {ptype!r}\n"
        f"TEMPLATE = {get_template(ptype).get('id')!r}\n"
        f"TEMPLATE_VERSION = {get_template(ptype).get('version')!r}\n"
        f"PLACEHOLDER = True\n"
        f"OVERVIEW = {overview!r}\n\n"
    )


def propose_changes(
    spec: RequirementSpec,
    design: DesignDoc,
    plan: ImplementationPlan,
) -> list[FileChange]:
    """Map ready plan items to deterministic file changes. Does not write."""
    if spec is None or design is None or plan is None:
        raise GenerationError("spec, design, and plan are required")
    if spec.status != SPEC_READY:
        raise GenerationError(f"Requirements not ready: {spec.status}")
    if plan.status != PLAN_READY:
        raise GenerationError(f"Plan not ready: {plan.status}")
    if spec.project_id != design.project_id or spec.project_id != plan.project_id:
        raise GenerationError("project_id mismatch")

    criterion_ids = [c.criterion_id for c in spec.acceptance_criteria]
    project_type = detect_project_type(spec.user_request)
    template = get_template(project_type)
    if not is_supported(project_type):
        raise GenerationError(
            f"Unsupported project type: {project_type}. {template.get('limitations')}"
        )
    changes: list[FileChange] = []
    overview = design.overview
    for item in plan.items:
        if not item.required:
            continue
        if item.task_id == "implement_core":
            if project_type == "cli":
                path = "src/cli.py"
                body = (
                    "import argparse\n\n"
                    "def main(argv=None) -> int:\n"
                    "    parser = argparse.ArgumentParser(description=OVERVIEW)\n"
                    "    parser.add_argument('input', nargs='?', help='optional input')\n"
                    "    args = parser.parse_args(argv)\n"
                    "    print(f'cli_ok:{args.input}')\n"
                    "    return 0\n\n"
                    "if __name__ == '__main__':\n"
                    "    raise SystemExit(main())\n"
                )
                init = (
                    '"""CLI package. Public API is main.\n"""\n'
                    "from src.cli import main\n"
                    "__all__ = ['main']\n"
                )
                changes.append(FileChange(path="src/__init__.py", content=init, plan_task_ids=[item.task_id], criterion_ids=criterion_ids))
            elif project_type == "library":
                path = "src/core.py"
                body = (
                    "def public_api(value: str) -> str:\n"
                    "    \"\"\"Return a labeled value. Deterministic stub.\"\"\"\n"
                    "    return f'library:{value}'\n"
                )
                init = (
                    '"""Library package. Public API is public_api.\n"""\n'
                    "from src.core import public_api\n"
                    "__all__ = ['public_api']\n"
                )
                changes.append(FileChange(path="src/__init__.py", content=init, plan_task_ids=[item.task_id], criterion_ids=criterion_ids))
            else:
                path = "src/core.py"
                body = (
                    "def hello(name: str = 'world') -> str:\n"
                    "    \"\"\"Return a greeting. Deterministic stub.\"\"\"\n"
                    "    return f'hello:{name}'\n"
                )
            content = _header(path, item.task_id, criterion_ids, overview) + body
            changes.append(FileChange(path=path, content=content, plan_task_ids=[item.task_id], criterion_ids=criterion_ids))
        elif item.task_id == "write_tests":
            if project_type == "cli":
                path = "tests/test_cli.py"
                body = (
                    "# Tests describe expected behavior. Not executed by Jarvis.\n"
                    "# Expect main([]) returns 0 and prints cli_ok:None.\n"
                )
            elif project_type == "library":
                path = "tests/test_core.py"
                body = (
                    "# Tests describe expected behavior. Not executed by Jarvis.\n"
                    "# Expect public_api('x') == 'library:x'.\n"
                )
            else:
                path = "tests/test_core.py"
                body = (
                    "# Tests describe expected behavior. Not executed by Jarvis.\n"
                    "# Expect hello('Ada') == 'hello:Ada'.\n"
                )
            content = _header(path, item.task_id, criterion_ids, overview) + body
            changes.append(FileChange(path=path, content=content, plan_task_ids=[item.task_id], criterion_ids=criterion_ids))
        elif item.task_id == "document":
            limits = "; ".join(template.get("limitations") or [])
            content = (
                f"# Project {spec.project_id}\n\n"
                f"{spec.user_request}\n\n"
                f"Template: {template.get('id')} {template.get('version')}\n"
                f"Limitations: {limits}\n"
                "PLACEHOLDER = True. Generated code is not executed.\n"
            )
            changes.append(FileChange(path="README.md", content=content, plan_task_ids=[item.task_id], criterion_ids=criterion_ids[:1]))
    if not changes:
        raise GenerationError("No generatable plan items")
    return changes


def prepare_generation(
    spec: RequirementSpec,
    design: DesignDoc,
    plan: ImplementationPlan,
    workspace: DevWorkspace,
    changes: Optional[list[FileChange]] = None,
) -> GenerationResult:
    """Validate changes without writing project files."""
    op_id = _new_id("gen_")
    result = GenerationResult(
        operation_id=op_id,
        project_id=spec.project_id if spec else "",
        success=False,
        backend=BACKEND_DETERMINISTIC,
    )
    try:
        proposed = changes if changes is not None else propose_changes(spec, design, plan)
    except GenerationError as exc:
        result.error = str(exc)
        return result

    seen: set[str] = set()
    for change in proposed:
        if not change.content or not str(change.content).strip():
            result.files.append(
                FileResult(
                    path=change.path,
                    status="rejected",
                    operation=change.operation,
                    error="empty content",
                    plan_task_ids=list(change.plan_task_ids),
                    criterion_ids=list(change.criterion_ids),
                )
            )
            continue
        if change.path in seen:
            result.files.append(
                FileResult(
                    path=change.path,
                    status="rejected",
                    error="duplicate target path",
                    plan_task_ids=list(change.plan_task_ids),
                )
            )
            continue
        seen.add(change.path)
        try:
            target = workspace.resolve(change.path)
        except WorkspaceError as exc:
            result.files.append(
                FileResult(
                    path=change.path,
                    status="rejected",
                    error=f"{exc.code}: {exc.message}",
                    plan_task_ids=list(change.plan_task_ids),
                )
            )
            continue
        exists = target.exists()
        if exists and not change.overwrite:
            result.files.append(
                FileResult(
                    path=change.path,
                    status="rejected",
                    operation="modify",
                    error="exists; overwrite not authorized",
                    plan_task_ids=list(change.plan_task_ids),
                    criterion_ids=list(change.criterion_ids),
                )
            )
            continue
        result.files.append(
            FileResult(
                path=change.path,
                status="prepared",
                operation="modify" if exists else "create",
                plan_task_ids=list(change.plan_task_ids),
                criterion_ids=list(change.criterion_ids),
            )
        )

    prepared = [f for f in result.files if f.status == "prepared"]
    rejected = [f for f in result.files if f.status == "rejected"]
    result.prepared = bool(prepared) and not rejected
    result.success = result.prepared
    result.notes = (
        "Prepared only. No files written."
        if result.prepared
        else "Preparation rejected one or more changes."
    )
    if rejected:
        result.error = "One or more changes rejected"
    return result


def apply_generation(
    workspace: DevWorkspace,
    changes: list[FileChange],
    prepared: GenerationResult,
    *,
    write_manifest: bool = True,
) -> GenerationResult:
    """Apply only changes that were prepared. Does not execute code."""
    if not prepared.prepared:
        prepared.applied = False
        prepared.success = False
        prepared.error = prepared.error or "Cannot apply an unprepared generation"
        return prepared

    prepared_paths = {f.path for f in prepared.files if f.status == "prepared"}
    by_path = {c.path: c for c in changes}
    applied_any = False
    failed = False

    for path in list(prepared_paths):
        change = by_path.get(path)
        if change is None:
            failed = True
            prepared.error = f"Missing change for prepared path {path}"
            continue
        try:
            workspace.write_text(
                change.path,
                change.content,
                overwrite=change.overwrite,
            )
            digest = _hash(change.content)
            for fr in prepared.files:
                if fr.path == path:
                    fr.status = "applied"
                    fr.sha256 = digest
            applied_any = True
        except Exception as exc:
            failed = True
            for fr in prepared.files:
                if fr.path == path:
                    fr.status = "failed"
                    fr.error = str(exc)
            prepared.error = f"Write failed for {path}: {exc}"

    prepared.applied = applied_any and not failed
    prepared.success = prepared.applied
    prepared.notes = (
        "Applied prepared changes. Generated code was not executed."
        if prepared.success
        else "Partial or failed apply."
    )

    if write_manifest and applied_any:
        try:
            manifest = prepared.to_dict()
            manifest["timestamp"] = _utcnow()
            import json

            workspace.write_text(
                f"artifacts/generation_{prepared.operation_id}.json",
                json.dumps(manifest, indent=2),
                overwrite=True,
            )
            prepared.manifest_path = f"artifacts/generation_{prepared.operation_id}.json"
        except Exception as exc:
            prepared.success = False
            prepared.error = f"Manifest write failed: {exc}"
            prepared.notes = "Files may have been written; manifest was not saved."
    return prepared
